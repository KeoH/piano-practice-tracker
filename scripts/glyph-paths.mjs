// Turns the music glyphs of the bundled Noto Music font into SVG paths (src/app/core/music-glyphs.ts), so the PDF
// export can draw them as vectors: PDF libraries cannot embed the woff2 the app ships, and the paths need no font.
//
//   node scripts/glyph-paths.mjs          writes src/app/core/music-glyphs.ts
//   node scripts/glyph-paths.mjs --check  only prints which glyphs the font has
//
// Noto Music is licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const FONT = 'node_modules/@fontsource/noto-music/files/noto-music-music-400-normal.woff';
const OUT = 'src/app/core/music-glyphs.ts';
/** Coordinates are written for a font size of 100, so a glyph at size `s` is scaled by `s / 100`. */
const EM = 100;
const GLYPHS = {
  treble: 0x1d11e,
  bass: 0x1d122,
  brace: 0x1d114,
  quarterRest: 0x1d13d,
  eighthRest: 0x1d13e,
  sixteenthRest: 0x1d13f,
  sharp: 0x266f,
  flat: 0x266d,
  natural: 0x266e,
};

const buf = readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const check = process.argv.includes('--check');

const entries = [];
let missing = 0;
for (const [name, cp] of Object.entries(GLYPHS)) {
  const glyph = font.charToGlyph(String.fromCodePoint(cp));
  const found = glyph.index !== 0 && glyph.unicode === cp;
  if (check) console.log(`${name.padEnd(14)} U+${cp.toString(16).toUpperCase().padEnd(6)} ${found ? 'ok' : 'MISSING'}`);
  if (!found) {
    missing++;
    continue;
  }
  const path = glyph.getPath(0, 0, EM);
  const box = path.getBoundingBox();
  entries.push([name, path.toPathData(2), (glyph.advanceWidth / font.unitsPerEm) * EM, [box.x1, box.y1, box.x2, box.y2].map((v) => +v.toFixed(2))]);
}
if (missing) {
  console.error(`${missing} glyph(s) missing from the font`);
  process.exit(1);
}
if (check) process.exit(0);

const body = entries
  .map(([name, d, adv, box]) => `  ${name}: { d: '${d}', advance: ${adv.toFixed(2)}, box: [${box.join(', ')}] },`)
  .join('\n');
writeFileSync(
  OUT,
  `/*
 * Music glyphs of the Noto Music font as SVG paths, for the PDF export. Generated by scripts/glyph-paths.mjs: do not edit.
 * Noto Music is licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).
 * Coordinates are for a font size of ${EM} with the origin on the baseline (y grows downwards); scale by \`size / ${EM}\`.
 */

export const GLYPH_EM = ${EM};

export interface GlyphPath {
  /** SVG path data. */
  d: string;
  /** Advance width, in the same units. */
  advance: number;
  /** Bounding box \`[x1, y1, x2, y2]\` (y grows downwards). */
  box: [number, number, number, number];
}

export const MUSIC_GLYPHS = {
${body}
} as const satisfies Record<string, GlyphPath>;

export type MusicGlyph = keyof typeof MUSIC_GLYPHS;
`,
);
console.log(`wrote ${OUT} (${entries.length} glyphs)`);
